def paint_face(img, u, v, w, h, base_color, noise_func=None, seed=0,
               stripes=None, spots=None, gradient=None, edge_darken=0.15):
    """
    Paint a rectangular face region on the texture.
    
    Args:
        img: PIL Image to paint on
        u, v: top-left corner in pixels
        w, h: width and height in pixels  
        base_color: RGBA base color
        noise_func: optional noise amplitude for texture variation
        seed: noise seed offset
        stripes: list of (position_fraction, color, width_fraction) for stripe bands
        spots: list of (x_frac, y_frac, radius_frac, color) for spot details
        gradient: (top_color, bottom_color) for vertical gradient
        edge_darken: amount to darken edges (0=none, 0.5=heavy)
    """
    draw = ImageDraw.Draw(img)
    for py in range(h):
        for px in range(w):
            x, y = u + px, v + py
            if x >= img.width or y >= img.height:
                continue
            
            color = list(base_color[:3])
            
            # Noise variation
            if noise_func and noise_func > 0:
                n = fbm(x, y, seed) * noise_func
                for i in range(3):
                    color[i] = clamp(color[i] + (n - 0.5) * 40)
            
            # Gradient (top to bottom)
            if gradient:
                t = py / max(1, h - 1)
                for i in range(3):
                    color[i] = clamp(lerp(gradient[0][i], gradient[1][i], t))
                if noise_func:
                    n = fbm(x, y, seed) * noise_func
                    for i in range(3):
                        color[i] = clamp(color[i] + (n - 0.5) * 30)
            
            # Stripes
            if stripes:
                for pos_frac, stripe_color, width_frac in stripes:
                    center = int(pos_frac * w)
                    half_w = int(width_frac * w / 2)
                    dist = abs(px - center)
                    if dist < half_w:
                        # Smooth stripe edges
                        blend = 1.0 - (dist / half_w)
                        blend = blend * blend * (3 - 2 * blend)  # smoothstep
                        for i in range(3):
                            color[i] = clamp(lerp(color[i], stripe_color[i], blend))
            
            # Edge darkening (bevel effect for 3D cube appearance)
            if edge_darken > 0:
                edge_dist = min(px, py, w - 1 - px, h - 1 - py)
                max_edge = min(w, h) * 0.25
                if max_edge > 0 and edge_dist < max_edge:
                    t = edge_dist / max_edge
                    dark = 1.0 - edge_darken * (1.0 - t)
                    for i in range(3):
                        color[i] = clamp(color[i] * dark)
            
            alpha = base_color[3] if len(base_color) > 3 else 255
            draw.point((x, y), fill=tuple(color[:3]) + (alpha,))


def paint_eye(img, u, v, size, iris_color, pupil_color):
    """Paint a detailed eye on the texture."""
    draw = ImageDraw.Draw(img)
    cx, cy = u + size // 2, v + size // 2
    r = size // 2
    for py in range(size):
        for px in range(size):
            x, y = u + px, v + py
            dx, dy = px - cx, py - cy
            dist = math.sqrt(dx*dx + dy*dy)
            if dist > r:
                continue
            # Sclera (white/yellow)
            if dist > r * 0.55:
                t = (dist - r * 0.55) / (r * 0.45)
                color = color_lerp(iris_color, (240, 230, 200), t)
            # Iris
            elif dist > r * 0.25:
                color = iris_color
                # Add radial streaks
                angle = math.atan2(dy, dx)
                streak = hash_noise(int(angle * 10), 0, 42)
                if streak > 0.6:
                    color = lighten(color, 0.15)
            # Pupil
            else:
                color = pupil_color
            draw.point((x, y), fill=color)


def paint_nose(img, u, v, w, h, color):
    """Paint a nose/muzzle detail."""
    draw = ImageDraw.Draw(img)
    for py in range(h):
        for px in range(w):
            x, y = u + px, v + py
            # Elliptical nose shape
            nx = (px - w/2) / (w/2)
            ny = (py - h/2) / (h/2)
            if nx*nx + ny*ny > 1.0:
                continue
            # Nostril dots
            n = fbm(x, y, 99)
            base = list(color[:3])
            if (nx - 0.2)**2 + (ny - 0.1)**2 < 0.08 or \
               (nx + 0.2)**2 + (ny - 0.1)**2 < 0.08:
                base = [clamp(v * 0.3) for v in base]
            draw.point((x, y), fill=tuple(base) + (255,))


