def hash_noise(x, y, seed=0):
    """Deterministic hash-based noise in [0,1]."""
    n = int(x * 12.9898 + y * 78.233 + seed * 43.758)
    n = (n << 13) ^ n
    return ((n * (n * n * 15731 + 789221) + 1376312589) & 0x7fffffff) / 2147483647.0

def smooth_noise(x, y, seed=0, scale=1.0):
    """Bilinear-interpolated smooth noise."""
    ix, iy = int(math.floor(x / scale)), int(math.floor(y / scale))
    fx, fy = (x / scale) - ix, (y / scale) - iy
    fx = fx * fx * (3 - 2 * fx)  # smoothstep
    fy = fy * fy * (3 - 2 * fy)
    v00 = hash_noise(ix, iy, seed)
    v10 = hash_noise(ix+1, iy, seed)
    v01 = hash_noise(ix, iy+1, seed)
    v11 = hash_noise(ix+1, iy+1, seed)
    return (v00*(1-fx)*(1-fy) + v10*fx*(1-fy) + v01*(1-fx)*fy + v11*fx*fy)

def fbm(x, y, seed=0, octaves=4, base_scale=8.0):
    """Fractal Brownian Motion for natural-looking variation."""
    value = 0.0
    amplitude = 1.0
    frequency = base_scale
    total_amp = 0.0
    for _ in range(octaves):
        value += smooth_noise(x, y, seed, frequency) * amplitude
        total_amp += amplitude
        amplitude *= 0.5
        frequency *= 2.0
    return value / total_amp

def lerp(a, b, t):
    return a + (b - a) * max(0, min(1, t))

def clamp(v, lo=0, hi=255):
    return max(lo, min(hi, int(v)))

def color_lerp(c1, c2, t):
    return tuple(clamp(lerp(a, b, t)) for a, b in zip(c1[:3], c2[:3])) + (255,)

def darken(c, factor):
    return tuple(clamp(v * factor) for v in c[:3]) + (255,)

def lighten(c, factor):
    return tuple(clamp(v + (255 - v) * factor) for v in c[:3]) + (255,)


