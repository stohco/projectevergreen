def improve_existing_texture(img, base_palette, noise_seed=0, 
                              stripe_func=None, detail_func=None):
    """
    Improve an existing texture by adding noise, stripes, and detail.
    Used for the textures that already exist but could be better.
    """
    w, h = img.size
    draw = ImageDraw.Draw(img)
    
    for y in range(h):
        for x in range(w):
            px = img.getpixel((x, y))
            if px[3] < 128:
                continue  # Skip transparent
            
            # Add noise variation
            n = fbm(x, y, noise_seed)
            noise_amt = 0.15
            new_color = [clamp(px[i] + (n - 0.5) * 40 * noise_amt) for i in range(3)]
            
            # Apply stripe function if provided
            if stripe_func:
                stripe_color = stripe_func(x, y, w, h)
                if stripe_color:
                    for i in range(3):
                        new_color[i] = clamp(lerp(new_color[i], stripe_color[i], 0.5))
            
            # Apply detail function if provided
            if detail_func:
                detail_color = detail_func(x, y, w, h)
                if detail_color:
                    for i in range(3):
                        new_color[i] = clamp(lerp(new_color[i], detail_color[i], 0.3))
            
            draw.point((x, y), fill=tuple(new_color) + (px[3],))
    
    return img


